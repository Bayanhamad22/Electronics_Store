CREATE OR REPLACE PACKAGE Order_Items_Package AS
PROCEDURE GETALLORDERITEMS;
PROCEDURE CREATEORDERITEMS(
UNIT_PRICE IN ORDER_ITEMS.unit_price%TYPE,
QUANTITY IN ORDER_ITEMS.quantity%TYPE,
ORDER_ID IN ORDER_ITEMS.order_id%TYPE,
PRODUCT_ID IN ORDER_ITEMS.product_id%TYPE);

PROCEDURE UPDATEORDERITEMS(ID IN NUMBER,
UNIT_PRICE IN ORDER_ITEMS.unit_price%TYPE,
QUANTITY IN ORDER_ITEMS.quantity%TYPE,
ORDER_ID IN ORDER_ITEMS.order_id%TYPE,
PRODUCT_ID IN ORDER_ITEMS.product_id%TYPE);
PROCEDURE DELETEORDERITEMS (ID IN NUMBER);
PROCEDURE GETORDERITEMSID(ID IN NUMBER);

END Order_Items_Package;


CREATE OR REPLACE PACKAGE BODY Order_Items_Package AS


PROCEDURE GETALLORDERITEMS AS
ORDERITEMS_ALL SYS_REFCURSOR;
BEGIN
open ORDERITEMS_ALL for
SELECT * FROM ORDER_ITEMS;
Dbms_sql.return_result(ORDERITEMS_ALL);
END GETALLORDERITEMS;

PROCEDURE CREATEORDERITEMS(
UNIT_PRICE IN ORDER_ITEMS.unit_price%TYPE,
QUANTITY IN ORDER_ITEMS.quantity%TYPE,
ORDER_ID IN ORDER_ITEMS.order_id%TYPE,
PRODUCT_ID IN ORDER_ITEMS.product_id%TYPE)
AS
BEGIN
INSERT INTO ORDER_ITEMS VALUES (DEFAULT,
UNIT_PRICE, QUANTITY, ORDER_ID, PRODUCT_ID);
COMMIT;
END CREATEORDERITEMS;


PROCEDURE UPDATEORDERITEMS(ID IN NUMBER,
UNIT_PRICE IN ORDER_ITEMS.unit_price%TYPE,
QUANTITY IN ORDER_ITEMS.quantity%TYPE,
ORDER_ID IN ORDER_ITEMS.order_id%TYPE,
PRODUCT_ID IN ORDER_ITEMS.product_id%TYPE)
AS
BEGIN
UPDATE ORDERITEMS SET 
unit_price = UNIT_PRICE,
quantity = QUANTITY,
order_id = ORDER_ID,
product_id = PRODUCT_ID 
WHERE order_item_id = ID;
COMMIT;
END UPDATEORDERITEMS;



PROCEDURE DELETEORDERITEMS (ID IN NUMBER)
AS
BEGIN
DELETE FROM ORDER_ITEMS WHERE order_item_id = ID;
COMMIT;
END DELETEORDERITEMS;


PROCEDURE GETORDERITEMSID(ID IN NUMBER)
AS
ORDERITEMS_ITEM SYS_REFCURSOR;
BEGIN
open ORDERITEMS_ITEM for select * from ORDER_ITEMS where order_item_id=ID;
DBMS_SQL.return_result(ORDERITEMS_ITEM);
END GETORDERITEMSID;


END Order_Items_Package;






