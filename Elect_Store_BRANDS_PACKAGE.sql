CREATE OR REPLACE PACKAGE Brands_Package AS
PROCEDURE GETALLBRANDS;
PROCEDURE CREATEBRANDS(BRAND_NAME IN BRANDS.brand_name%TYPE,BRAND_IMG_URL IN BRANDS.brand_img_url%TYPE);
PROCEDURE UPDATEBRANDS (ID IN NUMBER,BRAND_NAME IN BRANDS.brand_name%TYPE,BRAND_IMG_URL IN BRANDS.brand_img_url%TYPE);
PROCEDURE DELETEBRANDS (ID IN NUMBER);
PROCEDURE GETBRANDSID (ID IN NUMBER);

END Brands_Package;

CREATE OR REPLACE PACKAGE BODY Brands_Package AS

PROCEDURE GETALLBRANDS AS
BRANDS_ALL SYS_REFCURSOR;
BEGIN
open BRANDS_ALL for
SELECT * FROM BRANDS;
Dbms_sql.return_result(BRANDS_ALL);
END GETALLBRANDS;

PROCEDURE CREATEBRANDS
(BRAND_NAME IN BRANDS.brand_name%TYPE,
BRAND_IMG_URL IN BRANDS.brand_img_url%TYPE)
AS
BEGIN
INSERT INTO BRANDS VALUES (DEFAULT,
BRAND_NAME, BRAND_IMG_URL);
COMMIT;
END CREATEBRANDS;

PROCEDURE UPDATEBRANDS (ID IN NUMBER,
BRAND_NAME IN BRANDS.brand_name%TYPE,
BRAND_IMG_URL IN BRANDS.brand_img_url%TYPE)
AS
BEGIN
UPDATE BRANDS SET 
brand_name = BRAND_NAME,
brand_img_url = BRAND_IMG_URL
WHERE brand_id = ID;
COMMIT;
END UPDATEBRANDS;

PROCEDURE DELETEBRANDS (ID IN NUMBER)
AS
BEGIN
DELETE FROM BRANDS WHERE brand_id = ID;
COMMIT;
END DELETEBRANDS;

PROCEDURE GETBRANDSID(ID IN NUMBER)
AS
BRANDS_ITEM SYS_REFCURSOR;
BEGIN
open BRANDS_ITEM for select * from BRANDS where brand_id=ID;
DBMS_SQL.return_result(BRANDS_ITEM);
END GETBRANDSID;


END Brands_Package;