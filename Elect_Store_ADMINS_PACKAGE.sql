CREATE OR REPLACE PACKAGE Admins_Package AS
PROCEDURE GETALLADMINS;
PROCEDURE CREATEADMINS(USER_NAME IN ADMINS.username%TYPE,
PASSWORD_HASH IN ADMINS.password_hash%TYPE,EMAIL IN ADMINS.email%TYPE);
PROCEDURE UPDATEADMINS (ID IN NUMBER,USER_NAME IN ADMINS.username%TYPE,
PASSWORD_HASH IN ADMINS.password_hash%TYPE,EMAIL IN ADMINS.email%TYPE);
PROCEDURE DELETEADMINS (ID IN NUMBER);
PROCEDURE GETADMINSID(ID IN NUMBER);
END Admins_Package ;


CREATE OR REPLACE PACKAGE BODY Admins_Package AS

PROCEDURE GETALLADMINS AS
ADMINS_ALL SYS_REFCURSOR;
BEGIN
open ADMINS_ALL for
SELECT * FROM ADMINS;
Dbms_sql.return_result(ADMINS_ALL);
END GETALLADMINS;

PROCEDURE CREATEADMINS
(USER_NAME IN ADMINS.username%TYPE,
PASSWORD_HASH IN ADMINS.password_hash%TYPE,
EMAIL IN ADMINS.email%TYPE)
AS
BEGIN
INSERT INTO ADMINS VALUES (DEFAULT,
USER_NAME, PASSWORD_HASH, EMAIL);
COMMIT;
END CREATEADMINS;

PROCEDURE UPDATEADMINS (ID IN NUMBER,
USER_NAME IN ADMINS.username%TYPE,
PASSWORD_HASH IN ADMINS.password_hash%TYPE,
EMAIL IN ADMINS.email%TYPE)
AS
BEGIN
UPDATE ADMINS SET 
username = USER_NAME,
password_hash = PASSWORD_HASH,
email = EMAIL 
WHERE user_id = ID;
COMMIT;
END UPDATEADMINS;


PROCEDURE DELETEADMINS (ID IN NUMBER)
AS
BEGIN
DELETE FROM ADMINS WHERE user_id = ID;
COMMIT;
END DELETEADMINS;


PROCEDURE GETADMINSID(ID IN NUMBER)
AS
ADMINS_ITEM SYS_REFCURSOR;
BEGIN
open ADMINS_ITEM for select * from ADMINS where user_id=ID;
DBMS_SQL.return_result(ADMINS_ITEM);
END GETADMINSID;


END Admins_Package;