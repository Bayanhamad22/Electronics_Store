CREATE TABLE USERS (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR2(100) NOT NULL UNIQUE,
    phone_number VARCHAR2(50),
    profile_img_url VARCHAR2(255),
    password_hash VARCHAR2(255) NOT NULL,
    full_name VARCHAR2(100) NOT NULL,
    account_status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    user_role VARCHAR2(20) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    is_deleted CHAR(1) DEFAULT 'N' NOT NULL,

    CONSTRAINT chk_users_role
        CHECK (user_role IN ('ADMIN', 'CUSTOMER')),

    CONSTRAINT chk_users_status
        CHECK (account_status IN ('ACTIVE', 'INACTIVE', 'SUSPENDED')),

    CONSTRAINT chk_users_deleted
        CHECK (is_deleted IN ('Y', 'N'))
);


CREATE TABLE CATEGORIES (
    category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL UNIQUE
);


CREATE TABLE BRANDS (
    brand_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL UNIQUE
);


CREATE TABLE PRODUCTS (
    product_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(150) NOT NULL,
    description VARCHAR2(1000),
    price NUMBER(10,2) NOT NULL,
    warranty_information VARCHAR2(100),
    product_img_url VARCHAR2(255),
    status VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL,
    stock NUMBER DEFAULT 0 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    is_featured CHAR(1) DEFAULT 'N' NOT NULL,
    is_deleted CHAR(1) DEFAULT 'N' NOT NULL,
    brand_id NUMBER NOT NULL,
    category_id NUMBER NOT NULL,

    CONSTRAINT chk_products_price CHECK (price >= 0),
    CONSTRAINT chk_products_stock CHECK (stock >= 0),
    CONSTRAINT chk_products_status
        CHECK (status IN ('AVAILABLE', 'RESERVED', 'OUTOFSTOCK')),
    CONSTRAINT chk_products_featured
        CHECK (is_featured IN ('Y', 'N')),
    CONSTRAINT chk_products_deleted
        CHECK (is_deleted IN ('Y', 'N')),

    CONSTRAINT fk_products_brands
        FOREIGN KEY (brand_id) REFERENCES BRANDS(brand_id),

    CONSTRAINT fk_products_categories
        FOREIGN KEY (category_id) REFERENCES CATEGORIES(category_id)
);


CREATE TABLE PRODUCT_SPECIFICATIONS (
    product_spec_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    value VARCHAR2(255) NOT NULL,
    product_id NUMBER NOT NULL,

    CONSTRAINT fk_specs_products
        FOREIGN KEY (product_id) REFERENCES PRODUCTS(product_id)
);


CREATE TABLE ORDERS (
    order_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    total_amount NUMBER(10,2) NOT NULL,
    payment_method VARCHAR2(50) DEFAULT 'CASH_ON_DELIVERY' NOT NULL,
    order_status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    shipping_address VARCHAR2(255) NOT NULL,
    customer_phone_number VARCHAR2(50) NOT NULL,
    customer_full_name VARCHAR2(100) NOT NULL,
    user_id NUMBER NOT NULL,

    CONSTRAINT chk_orders_total CHECK (total_amount >= 0),
    CONSTRAINT chk_orders_payment
        CHECK (payment_method = 'CASH_ON_DELIVERY'),
    CONSTRAINT chk_orders_status
        CHECK (order_status IN ('PENDING', 'DELIVERED', 'CANCELLED')),

    CONSTRAINT fk_orders_users
        FOREIGN KEY (user_id) REFERENCES USERS(user_id)
);


CREATE TABLE ORDER_ITEMS (
    order_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_price NUMBER(10,2) NOT NULL,
    quantity NUMBER NOT NULL,
    order_id NUMBER NOT NULL,
    product_id NUMBER NOT NULL,

    CONSTRAINT chk_order_items_price
        CHECK (unit_price >= 0),

    CONSTRAINT chk_order_items_quantity
        CHECK (quantity > 0),

    CONSTRAINT uq_order_items_product
        UNIQUE (order_id, product_id),

    CONSTRAINT fk_items_orders
        FOREIGN KEY (order_id) REFERENCES ORDERS(order_id),

    CONSTRAINT fk_items_products
        FOREIGN KEY (product_id) REFERENCES PRODUCTS(product_id)
);