CREATE OR REPLACE PACKAGE BODY Users_Package AS

PROCEDURE GETALLUSERS AS
USERS_ALL SYS_REFCURSOR;
BEGIN
open USERS_ALL for
SELECT * FROM APP_USERS;
Dbms_sql.return_result(USERS_ALL);
END GETALLUSERS;

PROCEDURE CREATEUSERS
(EMAIL IN USERS.email%TYPE,
PHONE_NUMBER IN USERS.phone_number%TYPE,
PROFILE_IMG_URL IN USERS.profile_img_url%TYPE,
PASSWORD_HASH IN USERS.password_hash%TYPE,
FULL_NAME IN USERS.full_name%TYPE,
ACCOUNT_STATUS IN USERS.account_status%TYPE,
USER_ROLR IN USERS.user_role%TYPE,
CREATED_AT IN USERS.created_at%TYPE,
UPDATED_AT IN USERS.updated_at%TYPE,
IS_DELETED IN USERS.is_deleted%TYPE)
AS
BEGIN
INSERT INTO APP_USERS VALUES (DEFAULT,
EMAIL, PHONE_NUMBER, PROFILE_IMG_URL, PASSWORD_HASH,
FULL_NAME, ACCOUNT_STATUS, USER_ROLE,
CREATED_AT, UPDATED_AT, IS_DELETED);
COMMIT;
END CREATEUSERS;

PROCEDURE UPDATEUSERS (ID IN NUMBER,
EMAIL IN USERS.email%TYPE,
PHONE_NUMBER IN USERS.phone_number%TYPE,
PROFILE_IMG_URL IN USERS.profile_img_url%TYPE,
PASSWORD_HASH IN USERS.password_hash%TYPE,
FULL_NAME IN USERS.full_name%TYPE,
ACCOUNT_STATUS IN USERS.account_status%TYPE,
USER_ROLR IN USERS.user_role%TYPE,
CREATED_AT IN USERS.created_at%TYPE,
UPDATED_AT IN USERS.updated_at%TYPE,
IS_DELETED IN USERS.is_deleted%TYPE)
AS
BEGIN
UPDATE APP_USERS SET 
email = EMAIL,
phone_number = PHONE_NUMBER,
profile_img_url = PROFILE_IMG_URL,
password_hash = PASSWORD_HASH,
account_status = ACCOUNT_STATUS,
user_role = USER_ROLE,
created_at = CREATED_AT,
updated_at = UPDATED_AT,
is_deleted = IS_DELETED
WHERE user_id = ID;
COMMIT;
END UPDATEUSERS;


PROCEDURE DELETEUSERS (ID IN NUMBER)
AS
BEGIN
DELETE FROM USERS WHERE user_id = ID;
COMMIT;
END DELETEUSERS;


PROCEDURE GETUSERSID(ID IN NUMBER)
AS
USERS_ITEM SYS_REFCURSOR;
BEGIN
open USERS_ITEM for select * from USERS where user_id=ID;
DBMS_SQL.return_result(USERS_ITEM);
END GETUSERSID;


END Users_Package;