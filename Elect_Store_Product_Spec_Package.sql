CREATE OR REPLACE PACKAGE Product_Spec_Package AS
PROCEDURE GETSPECIFICATIONS;
PROCEDURE CREATESPECIFICATIONS(
NAME IN PRODUCT_SPECIFICATIONS.name%TYPE,
VALUE IN PRODUCT_SPECIFICATIONS.value%TYPE,
PRODUCT_ID IN PRODUCT_SPECIFICATIONS.product_id%TYPE);

PROCEDURE UPDATESPECIFICATIONS (ID IN NUMBER,
NAME IN PRODUCT_SPECIFICATIONS.name%TYPE,
VALUE IN PRODUCT_SPECIFICATIONS.value%TYPE,
PRODUCT_ID IN PRODUCT_SPECIFICATIONS.product_id%TYPE);
PROCEDURE DELETESPECIFICATIONS (ID IN NUMBER);
PROCEDURE GETSPECIFICATIONSID(ID IN NUMBER);
END Product_Spec_Package;


CREATE OR REPLACE PACKAGE BODY Product_Spec_Package AS


PROCEDURE GETSPECIFICATIONS AS
SPEC_ALL SYS_REFCURSOR;
BEGIN
open SPEC_ALL for
SELECT * FROM PRODUCT_SPECIFICATIONS;
Dbms_sql.return_result(SPEC_ALL);
END GETSPECIFICATIONS;

PROCEDURE CREATESPECIFICATIONS
(NAME IN PRODUCT_SPECIFICATIONS.name%TYPE,
VALUE IN PRODUCT_SPECIFICATIONS.value%TYPE,
PRODUCT_ID IN PRODUCT_SPECIFICATIONS.product_id%TYPE)
AS
BEGIN
INSERT INTO PRODUCT_SPECIFICATIONS VALUES (DEFAULT,
NAME, VALUE, PRODUCT_ID);
COMMIT;
END CREATESPECIFICATIONS;

PROCEDURE UPDATESPECIFICATIONS (ID IN NUMBER,
NAME IN PRODUCT_SPECIFICATIONS.name%TYPE,
VALUE IN PRODUCT_SPECIFICATIONS.value%TYPE,
PRODUCT_ID IN PRODUCT_SPECIFICATIONS.product_id%TYPE)
AS
BEGIN
UPDATE PRODUCT_SPECIFICATIONS SET 
name = NAME,
value = VALUE,
product_id = PRODUCT_ID 
WHERE product_spec_id = ID;
COMMIT;
END UPDATESPECIFICATIONS;

PROCEDURE DELETESPECIFICATIONS (ID IN NUMBER)
AS
BEGIN
DELETE FROM PRODUCT_SPECIFICATIONS WHERE product_spec_id = ID;
COMMIT;
END DELETESPECIFICATIONS;



PROCEDURE GETSPECIFICATIONSID(ID IN NUMBER)
AS
SPEC_ITEM SYS_REFCURSOR;
BEGIN
open SPEC_ITEM for select * from PRODUCT_SPECIFICATIONS where product_spec_id=ID;
DBMS_SQL.return_result(SPEC_ITEM);
END GETSPECIFICATIONSID;


END Product_Spec_Package;