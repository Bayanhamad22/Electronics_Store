CREATE TABLE CATEGORYS (
category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
category_name VARCHAR2 (100) NOT NULL
);

CREATE TABLE BRANDS (
brand_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
brand_name VARCHAR2(100) NOT NULL,
brand_img_url VARCHAR2(255)NOT NULL 
);

CREATE TABLE ADMINS (
user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
username VARCHAR2(50) NOT NULL,
password_hash VARCHAR2(255) NOT NULL,
email VARCHAR2(100)NOT NULL
);

CREATE TABLE PRODUCTS (
product_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
product_name VARCHAR2(150) NOT NULL,
descriptions VARCHAR2(1000),
price NUMBER(10, 2) NOT NULL,
warranty_info VARCHAR2(100),
stock_quantity NUMBER NOT NULL,
status VARCHAR2(50) DEFAULT 'AVAILABLE',
created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
is_featured CHAR(1) DEFAULT 'N',
brand_id NUMBER,
category_id NUMBER,
CONSTRAINT "CHK_PRODUCTS_STATUS" CHECK ( status IN ('AVAILABLE','RESERVED', 'OUT OF STOCK')) ENABLE,
CONSTRAINT "CHK_IS_FEATURED" CHECK (is_featured IN ('Y', 'N'))ENABLE,
CONSTRAINT prod_brands_FK FOREIGN KEY (brand_id) REFERENCES BRANDS(brand_id) ON DELETE CASCADE,
CONSTRAINT prod_categorys_FK FOREIGN KEY (category_id) REFERENCES CATEGORYS(category_id) ON DELETE CASCADE    
);

CREATE TABLE PRODUCT_SPECIFICATIONS (
spec_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
spec_name VARCHAR2(100) NOT NULL,
spec_value VARCHAR2(255) NOT NULL,
product_id NUMBER NOT NULL,
CONSTRAINT spec_products_FK FOREIGN KEY (product_id) REFERENCES PRODUCTS(product_id) ON DELETE CASCADE
);

CREATE TABLE ORDERS(
order_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
shipping_address VARCHAR2(255) NOT NULL,
payment_method VARCHAR2(50) NOT NULL,
total_amount NUMBER(10, 2) NOT NULL,
status VARCHAR2(50) DEFAULT 'PENDING',
fall_name VARCHAR2(100) NOT NULL,
phone VARCHAR2(50) NOT NULL,
created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
update_at TIMESTAMP,
CONSTRAINT "CHK_ORDERS_STATUS" CHECK ( status IN ('PENDING','DELIVERED','CANCELLED')) ENABLE
);

CREATE TABLE ORDERITEMS (
order_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
unit_price NUMBER(10, 2) NOT NULL,
quantity NUMBER NOT NULL,
product_id NUMBER NOT NULL,
order_id NUMBER NOT NULL,
CONSTRAINT item_product_FK FOREIGN KEY (product_id) REFERENCES PRODUCTS(product_id),
CONSTRAINT item_order_FK FOREIGN KEY (order_id) REFERENCES ORDERS(order_id) ON DELETE CASCADE
);









