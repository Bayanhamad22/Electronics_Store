CREATE OR REPLACE PACKAGE OrderItems_Package AS
PROCEDURE GETALLORDERITEMS;
PROCEDURE CREATEORDERITEMS
(UNIT_PRICE IN ORDERITEMS.unit_price%TYPE,
QUANTITY IN ORDERITEMS.quantity%TYPE,
PRODUCT_ID IN ORDERITEMS.product_id%TYPE,
ORDER_ID IN ORDERITEMS.order_id%TYPE);
PROCEDURE UPDATEORDERITEMS(ID IN NUMBER,
UNIT_PRICE IN ORDERITEMS.unit_price%TYPE,
QUANTITY IN ORDERITEMS.quantity%TYPE,
PRODUCT_ID IN ORDERITEMS.product_id%TYPE,
ORDER_ID IN ORDERITEMS.order_id%TYPE);
PROCEDURE DELETEORDERITEMS (ID IN NUMBER);
PROCEDURE GETORDERITEMSID(ID IN NUMBER);

END OrderItems_Package;


CREATE OR REPLACE PACKAGE BODY OrderItems_Package AS


PROCEDURE GETALLORDERITEMS AS
ORDERITEMS_ALL SYS_REFCURSOR;
BEGIN
open ORDERITEMS_ALL for
SELECT * FROM ORDERITEMS;
Dbms_sql.return_result(ORDERITEMS_ALL);
END GETALLORDERITEMS;

PROCEDURE CREATEORDERITEMS
(UNIT_PRICE IN ORDERITEMS.unit_price%TYPE,
QUANTITY IN ORDERITEMS.quantity%TYPE,
PRODUCT_ID IN ORDERITEMS.product_id%TYPE,
ORDER_ID IN ORDERITEMS.order_id%TYPE)
AS
BEGIN
INSERT INTO ORDERITEMS VALUES (DEFAULT,
UNIT_PRICE, QUANTITY, PRODUCT_ID, ORDER_ID);
COMMIT;
END CREATEORDERITEMS;


PROCEDURE UPDATEORDERITEMS(ID IN NUMBER,
UNIT_PRICE IN ORDERITEMS.unit_price%TYPE,
QUANTITY IN ORDERITEMS.quantity%TYPE,
PRODUCT_ID IN ORDERITEMS.product_id%TYPE,
ORDER_ID IN ORDERITEMS.order_id%TYPE)
AS
BEGIN
UPDATE ORDERITEMS SET 
unit_price = UNIT_PRICE,
quantity = QUANTITY,
product_id = PRODUCT_ID,
order_id = ORDER_ID 
WHERE order_item_id = ID;
COMMIT;
END UPDATEORDERITEMS;



PROCEDURE DELETEORDERITEMS (ID IN NUMBER)
AS
BEGIN
DELETE FROM ORDERITEMS WHERE order_item_id = ID;
COMMIT;
END DELETEORDERITEMS;


PROCEDURE GETORDERITEMSID(ID IN NUMBER)
AS
ORDERITEMS_ITEM SYS_REFCURSOR;
BEGIN
open ORDERITEMS_ITEM for select * from ORDERITEMS where order_item_id=ID;
DBMS_SQL.return_result(ORDERITEMS_ITEM);
END GETORDERITEMSID;


END OrderItems_Package;






