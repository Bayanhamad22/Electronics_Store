PROCEDURE GETALLORDERS;
PROCEDURE CREATEORDERS
(TOTAL_AMOUNT IN ORDERS.total_amount%TYPE,
PAYMENT_METHOD IN ORDERS.payment_method%TYPE,
ORDER_STATUS IN ORDERS.order_status%TYPE,
CREATED_AT IN ORDERS.created_at%TYPE,
UPDATED_AT IN ORDERS.updated_at%TYPE,
SHIPPING_ADDRESS IN ORDERS.shipping_address%TYPE,
CUSTOMER_PHONR_NUMBER IN ORDERS.customer_phone_number%TYPE,
CUSTOMER_FULL_NAME IN ORDERS.customer_full_name%TYPE,
USER_ID IN ORDERS.user_id%TYPE);

PROCEDURE UPDATEORDERS (ID IN NUMBER,
TOTAL_AMOUNT IN ORDERS.total_amount%TYPE,
PAYMENT_METHOD IN ORDERS.payment_method%TYPE,
ORDER_STATUS IN ORDERS.order_status%TYPE,
CREATED_AT IN ORDERS.created_at%TYPE,
UPDATED_AT IN ORDERS.updated_at%TYPE,
SHIPPING_ADDRESS IN ORDERS.shipping_address%TYPE,
CUSTOMER_PHONR_NUMBER IN ORDERS.customer_phone_number%TYPE,
CUSTOMER_FULL_NAME IN ORDERS.customer_full_name%TYPE,
USER_ID IN ORDERS.user_id%TYPE);
PROCEDURE DELETEORDERS (ID IN NUMBER);
PROCEDURE GETORDERSID(ID IN NUMBER);

END Orders_Package;

CREATE OR REPLACE PACKAGE BODY Orders_Package AS


PROCEDURE GETALLORDERS AS
ORDERS_ALL SYS_REFCURSOR;
BEGIN
open ORDERS_ALL for
SELECT * FROM ORDERS;
Dbms_sql.return_result(ORDERS_ALL);
END GETALLORDERS;

PROCEDURE CREATEORDERS
(TOTAL_AMOUNT IN ORDERS.total_amount%TYPE,
PAYMENT_METHOD IN ORDERS.payment_method%TYPE,
ORDER_STATUS IN ORDERS.order_status%TYPE,
CREATED_AT IN ORDERS.created_at%TYPE,
UPDATED_AT IN ORDERS.updated_at%TYPE,
SHIPPING_ADDRESS IN ORDERS.shipping_address%TYPE,
CUSTOMER_PHONR_NUMBER IN ORDERS.customer_phone_number%TYPE,
CUSTOMER_FULL_NAME IN ORDERS.customer_full_name%TYPE,
USER_ID IN ORDERS.user_id%TYPE)
AS
BEGIN
INSERT INTO ORDERS VALUES (DEFAULT,
TOTAL_AMOUNT, PAYMENT_METHOD, ORDER_STATUS,
CREATED_AT, UPDATED_AT ,SHIPPING_ADDRESS,
CUSTOMER_PHONR_NUMBER, CUSTOMER_FULL_NAME, USER_ID);
COMMIT;
END CREATEORDERS;

PROCEDURE UPDATEORDERS (ID IN NUMBER,
TOTAL_AMOUNT IN ORDERS.total_amount%TYPE,
PAYMENT_METHOD IN ORDERS.payment_method%TYPE,
ORDER_STATUS IN ORDERS.order_status%TYPE,
CREATED_AT IN ORDERS.created_at%TYPE,
UPDATED_AT IN ORDERS.updated_at%TYPE,
SHIPPING_ADDRESS IN ORDERS.shipping_address%TYPE,
CUSTOMER_PHONR_NUMBER IN ORDERS.customer_phone_number%TYPE,
CUSTOMER_FULL_NAME IN ORDERS.customer_full_name%TYPE,
USER_ID IN ORDERS.user_id%TYPE)
AS
BEGIN
UPDATE ORDERS SET 
total_amount = TOTAL_AMOUNT,
payment_method = PAYMENT_METHOD,
order_status = ORDER_STATUS,
created_at = CREATED_AT,
updated_at = UPDATED_AT,
shipping_address = SHIPPING_ADDRESS,
customer_phone_number = CUSTOMER_PHONR_NUMBER,
customer_full_name = CUSTOMER_FULL_NAME,
user_id = USER_ID
WHERE order_id = ID;
COMMIT;
END UPDATEORDERS;

PROCEDURE DELETEORDERS (ID IN NUMBER)
AS
BEGIN
DELETE FROM ORDERS WHERE order_id = ID;
COMMIT;
END DELETEORDERS;

PROCEDURE GETORDERSID(ID IN NUMBER)
AS
ORDERS_ITEM SYS_REFCURSOR;
BEGIN
open ORDERS_ITEM for select * from ORDERS where order_id=ID;
DBMS_SQL.return_result(ORDERS_ITEM);
END GETORDERSID;



END Orders_Package;
