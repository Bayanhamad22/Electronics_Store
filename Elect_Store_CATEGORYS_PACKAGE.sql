CREATE OR REPLACE PACKAGE Categorys_Package AS
PROCEDURE GETAllCATEGORYS ;
PROCEDURE CREATECATEGORYS(CATEGORYS_NAME IN CATEGORYS.category_name%TYPE);
PROCEDURE UPDATECATEGORYS (ID IN NUMBER,CATEGORYS_NAME IN CATEGORYS.category_name%TYPE);
PROCEDURE DELETECATEGORYS (ID IN NUMBER);
PROCEDURE GETCATEGORYSID(ID IN NUMBER);

END Categorys_Package;



CREATE OR REPLACE PACKAGE BODY Categorys_Package AS

PROCEDURE GETAllCATEGORYS AS
CATE_ALL SYS_REFCURSOR;
BEGIN
open CATE_ALL for
SELECT * FROM CATEGORYS;
Dbms_sql.return_result(CATE_ALL);
END GETAllCATEGORYS;

PROCEDURE CREATECATEGORYS
(CATEGORYS_NAME IN CATEGORYS.category_name%TYPE)
AS
BEGIN
INSERT INTO CATEGORYS VALUES 
(DEFAULT, CATEGORYS_NAME);
COMMIT;
END CREATECATEGORYS;

PROCEDURE UPDATECATEGORYS (ID IN NUMBER,
CATEGORYS_NAME IN CATEGORYS.category_name%TYPE)
AS
BEGIN
UPDATE CATEGORYS SET 
category_name = CATEGORYS_NAME
WHERE category_id = ID;
COMMIT;
END UPDATECATEGORYS;

PROCEDURE DELETECATEGORYS (ID IN NUMBER)
AS
BEGIN
DELETE FROM CATEGORYS WHERE category_id = ID;
COMMIT;
END DELETECATEGORYS;


PROCEDURE GETCATEGORYSID(ID IN NUMBER)
AS
CATE_ITEM SYS_REFCURSOR;
BEGIN
open CATE_ITEM for select * from CATEGORYS where category_id=ID;
DBMS_SQL.return_result(CATE_ITEM);
END GETCATEGORYSID;


END Categorys_Package;
















