CREATE OR REPLACE PACKAGE Categories_Package AS
PROCEDURE GETAllCATEGORIES ;
PROCEDURE CREATECATEGORIES(NAME IN CATEGORIES.name%TYPE);
PROCEDURE UPDATECATEGORIES (ID IN NUMBER,NAME IN CATEGORIES.name%TYPE);
PROCEDURE DELETECATEGORIES (ID IN NUMBER);
PROCEDURE GETCATEGORIESID(ID IN NUMBER);

END Categories_Package;



CREATE OR REPLACE PACKAGE BODY Categories_Package AS

PROCEDURE GETAllCATEGORIES AS
CATE_ALL SYS_REFCURSOR;
BEGIN
open CATE_ALL for
SELECT * FROM CATEGORIES;
Dbms_sql.return_result(CATE_ALL);
END GETAllCATEGORIES;

PROCEDURE CREATECATEGORIES
(NAME IN CATEGORIES.name%TYPE)
AS
BEGIN
INSERT INTO CATEGORIES VALUES 
(DEFAULT, NAME);
COMMIT;
END CREATECATEGORYS;

PROCEDURE UPDATECATEGORIES (ID IN NUMBER,
NAME IN CATEGORIES.name%TYPE)
AS
BEGIN
UPDATE CATEGORIES SET 
name = NAME
WHERE category_id = ID;
COMMIT;
END UPDATECATEGORIES;

PROCEDURE DELETECATEGORIES (ID IN NUMBER)
AS
BEGIN
DELETE FROM CATEGORIES WHERE category_id = ID;
COMMIT;
END DELETECATEGORIES;


PROCEDURE GETCATEGORIESID(ID IN NUMBER)
AS
CATE_ITEM SYS_REFCURSOR;
BEGIN
open CATE_ITEM for select * from CATEGORIES where category_id=ID;
DBMS_SQL.return_result(CATE_ITEM);
END GETCATEGORIESID;


END Categories_Package;
















