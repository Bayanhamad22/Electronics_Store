BRAND_ID IN PRODUCTS.brand_id%TYPE,
CATEGORY_ID IN PRODUCTS.category_id%TYPE);

PROCEDURE DELETEPRODUCTS (ID IN NUMBER);
PROCEDURE GETPRODUCTSID(ID IN NUMBER);

END Products_Package;


CREATE OR REPLACE PACKAGE BODY Products_Package AS


PROCEDURE GETALLPRODUCTS AS
PRODUCTS_ALL SYS_REFCURSOR;
BEGIN
open PRODUCTS_ALL for
SELECT * FROM PRODUCTS;
Dbms_sql.return_result(PRODUCTS_ALL);
END GETALLPRODUCTS;

PROCEDURE CREATEPRODUCTS
(NAME IN PRODUCTS.name%TYPE,
DESCRIPION IN PRODUCTS.description%TYPE,
PRICE IN PRODUCTS.price%TYPE,
WARRANTY_INFORMATION IN PRODUCTS.warranty_information%TYPE,
PRODECT_IMG_URL IN PRODUCTS.product_img_url%TYPE,
STATUS IN PRODUCTS.status%TYPE,
STOCK IN PRODUCTS.stock%TYPE,
CREATED_AT IN PRODUCTS.created_at%TYPE,
UPDATED_AT IN PRODUCTS.updated_at%TYPE,
IS_FEATURED IN PRODUCTS.is_featured%TYPE,
IS_DELETED IN PRODUCTS.is_deleted%TYPE,
BRAND_ID IN PRODUCTS.brand_id%TYPE,
CATEGORY_ID IN PRODUCTS.category_id%TYPE)
AS
BEGIN
INSERT INTO PRODUCTS VALUES (DEFAULT,
PRODUCT_NAME, DESCRIPIONS, PRICE,WARRANTY_INFO,
STOCK_QUANTITY, STATUS, PRODECT_IMG_URL, CREATED_AT,
IS_FEATURED,IS_DELETED, BRAND_ID,CATEGORY_ID);
COMMIT;
END CREATEPRODUCTS;


PROCEDURE UPDATEPRODUCTS (ID IN NUMBER,
NAME IN PRODUCTS.name%TYPE,
DESCRIPION IN PRODUCTS.description%TYPE,
PRICE IN PRODUCTS.price%TYPE,
WARRANTY_INFORMATION IN PRODUCTS.warranty_information%TYPE,
PRODECT_IMG_URL IN PRODUCTS.product_img_url%TYPE,
STATUS IN PRODUCTS.status%TYPE,
STOCK IN PRODUCTS.stock%TYPE,
CREATED_AT IN PRODUCTS.created_at%TYPE,
UPDATED_AT IN PRODUCTS.updated_at%TYPE,
IS_FEATURED IN PRODUCTS.is_featured%TYPE,
IS_DELETED IN PRODUCTS.is_deleted%TYPE,
BRAND_ID IN PRODUCTS.brand_id%TYPE,
CATEGORY_ID IN PRODUCTS.category_id%TYPE)
AS
BEGIN
UPDATE PRODUCTS SET 
name = NAME,
description = DESCRIPION,
price = PRICE ,
warranty_information = WARRANTY_INFORMATION,
product_img_url = PRODECT_IMG_URL,
status = STATUS,
stock = STOCK,
created_at = CREATED_AT,
updated_at = UPDATED_AT,
is_featured = IS_FEATURED,
is_deleted = IS_DELETED,
brand_id = BRAND_ID,
category_id = CATEGORY_ID
WHERE product_id = ID;
COMMIT;
END UPDATEPRODUCTS;

PROCEDURE DELETEPRODUCTS (ID IN NUMBER)
AS
BEGIN
DELETE FROM PRODUCTS WHERE product_id = ID;
COMMIT;
END DELETEPRODUCTS;

PROCEDURE GETPRODUCTSID(ID IN NUMBER)
AS
PRODUCTS_ITEM SYS_REFCURSOR;
BEGIN
open PRODUCTS_ITEM for select * from PRODUCTS where product_id=ID;
DBMS_SQL.return_result(PRODUCTS_ITEM);
END GETPRODUCTSID;


END Products_Package;

